def cellbm(sc, co):
    return glyph(sc), co

def draw_screen(scene_fn, name, desc, salidas, ves, prompt):
    cells = [[(32, 0)] * 40 for _ in range(25)]
    s = scene_fn()
    for r in range(10):
        for c in range(40): cells[r][c] = s.grid[r][c]
    def put(x, y, text, co, font=True):
        for k, ch in enumerate(text):
            if x + k >= 40: break
            cells[y][x + k] = ('F' + ch, co)   # mark as font char
    put(1, 10, name, 7)
    dl = 12
    for seg in desc.split("/"):
        put(1, dl, seg[:38], 15); dl += 1
    put(1, 21, "salidas: " + salidas, 3)
    put(1, 22, ves, 13)
    put(0, 23, prompt, 14)
    # render
    W, H = 40 * 8, 25 * 8
    px = bytearray(W * H * 3)
    bg = PAL[6]  # border-ish dark
    for r in range(25):
        for c in range(40):
            v, co = cells[r][c]
            col = PAL[co & 15]
            if isinstance(v, str) and v.startswith('F'):
                bm = FONT.get(v[1], FONT[' '])
            else:
                bm = glyph(v)
            for yy in range(8):
                rowb = bm[yy]
                for xx in range(8):
                    if rowb & (0x80 >> xx):
                        X, Y = c * 8 + xx, r * 8 + yy
                        o = (Y * W + X) * 3; px[o:o+3] = bytes(col)
    return px, W, H

def scale(px, W, H, k=2):
    W2, H2 = W*k, H*k; o2 = bytearray(W2*H2*3)
    for y in range(H2):
        sy = y//k
        for x in range(W2):
            sx = x//k; o = (sy*W+sx)*3; oo = (y*W2+x)*3; o2[oo:oo+3] = px[o:o+3]
    return o2, W2, H2

